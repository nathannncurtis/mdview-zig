const std = @import("std");
const Writer = std.Io.Writer;
const files = @import("files.zig");

const sections = [_][]const u8{
    "Backslash escapes",
    "Entity and numeric character references",
    "Code spans",
    "Emphasis and strong emphasis",
    "Strikethrough (extension)",
    "Textual content",
};

const html_sections = [_][]const u8{ "HTML blocks", "Raw HTML", "Disallowed Raw HTML (extension)" };

const fence = "````````````````````````````````";

fn inList(list: []const []const u8, section: []const u8) bool {
    for (list) |s| if (std.mem.eql(u8, s, section)) return true;
    return false;
}

fn literal(w: *Writer, s: []const u8) Writer.Error!void {
    try w.writeByte('"');
    for (s) |ch| switch (ch) {
        '\\' => try w.writeAll("\\\\"),
        '"' => try w.writeAll("\\\""),
        '\n' => try w.writeAll("\\n"),
        '\t' => try w.writeAll("\\t"),
        '\r' => try w.writeAll("\\r"),
        0...8, 11, 12, 14...0x1F, 0x7F => try w.print("\\x{x:0>2}", .{ch}),
        else => try w.writeByte(ch),
    };
    try w.writeByte('"');
}

fn heading(line: []const u8) ?[]const u8 {
    var n: usize = 0;
    while (n < line.len and line[n] == '#') n += 1;
    if (n < 1 or n > 6 or n >= line.len or line[n] != ' ') return null;
    return line[n + 1 ..];
}

fn block(arena: std.mem.Allocator, lines: []const []const u8) ![]u8 {
    if (lines.len == 0) return arena.dupe(u8, "");
    var buf: std.ArrayList(u8) = .empty;
    for (lines) |l| {
        try buf.appendSlice(arena, l);
        try buf.append(arena, '\n');
    }
    return std.mem.replaceOwned(u8, arena, buf.items, "\xe2\x86\x92", "\t");
}

const Case = struct { number: usize, section: []const u8, md: []const u8, html: []const u8 };

pub fn main(init: std.process.Init) !void {
    const all_args = try init.minimal.args.toSlice(init.arena.allocator());
    if (all_args.len != 3 and all_args.len != 4) {
        files.say(init.io, "usage: gen-spec-cases <spec.txt> <out.zig> [<html-cases.json>]\n", .{});
        return error.Usage;
    }
    const a = all_args[1..];
    const arena = init.arena.allocator();
    const raw = try files.read(init.io, arena, a[0]);
    const text = try std.mem.replaceOwned(u8, arena, raw, "\r\n", "\n");

    var all: std.ArrayList([]const u8) = .empty;
    var split = std.mem.splitScalar(u8, text, '\n');
    while (split.next()) |l| try all.append(arena, l);
    const lines = all.items;

    var cases: std.ArrayList(Case) = .empty;
    var html_cases: std.ArrayList(Case) = .empty;
    var section: []const u8 = "";
    var number: usize = 0;
    var i: usize = 0;
    while (i < lines.len) : (i += 1) {
        const line = lines[i];
        if (!std.mem.startsWith(u8, line, "```")) {
            if (heading(line)) |h| section = h;
        }
        if (!std.mem.startsWith(u8, line, fence ++ " example")) continue;
        number += 1;
        i += 1;
        var md: std.ArrayList([]const u8) = .empty;
        var html: std.ArrayList([]const u8) = .empty;
        var cur = &md;
        while (!std.mem.startsWith(u8, lines[i], fence)) : (i += 1) {
            if (std.mem.eql(u8, lines[i], ".")) cur = &html else try cur.append(arena, lines[i]);
        }
        const case: Case = .{
            .number = number,
            .section = section,
            .md = try block(arena, md.items),
            .html = try block(arena, html.items),
        };
        if (inList(&sections, section)) try cases.append(arena, case);
        if (inList(&html_sections, section)) try html_cases.append(arena, case);
    }

    var out: Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("// Generated by tools/gen_spec_cases.zig from the GFM spec (github/cmark-gfm test/spec.txt).\n");
    try w.writeAll("pub const Case = struct { number: u32, section: []const u8, md: []const u8, html: []const u8 };\n\n");
    try w.writeAll("pub const cases = [_]Case{\n");
    for (cases.items) |c| {
        try w.print("    .{{ .number = {d}, .section = ", .{c.number});
        try literal(w, c.section);
        try w.writeAll(", .md = ");
        try literal(w, c.md);
        try w.writeAll(", .html = ");
        try literal(w, c.html);
        try w.writeAll(" },\n");
    }
    try w.writeAll("};\n");
    try files.write(init.io, a[1], out.written());
    if (a.len == 3) {
        var json: Writer.Allocating = .init(arena);
        const jw = &json.writer;
        try jw.writeAll("[\n");
        for (html_cases.items, 0..) |c, k| {
            try jw.print("{{\"n\": {d}, \"section\": ", .{c.number});
            try std.json.Stringify.encodeJsonString(c.section, .{}, jw);
            try jw.writeAll(", \"md\": ");
            try std.json.Stringify.encodeJsonString(c.md, .{}, jw);
            try jw.writeAll(", \"html\": ");
            try std.json.Stringify.encodeJsonString(c.html, .{}, jw);
            try jw.writeAll(if (k + 1 < html_cases.items.len) "},\n" else "}\n");
        }
        try jw.writeAll("]\n");
        try files.write(init.io, a[2], json.written());
    }
    files.say(init.io, "{d} cases, {d} html cases\n", .{ cases.items.len, html_cases.items.len });
}
