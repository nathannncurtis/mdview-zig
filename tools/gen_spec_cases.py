import re
import sys

SECTIONS = {
    "Backslash escapes",
    "Entity and numeric character references",
    "Code spans",
    "Emphasis and strong emphasis",
    "Strikethrough (extension)",
    "Textual content",
}


def literal(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main(spec_path, out_path):
    text = open(spec_path, encoding="utf-8").read().replace("\r\n", "\n")
    section = ""
    cases = []
    number = 0
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^#{1,6} (.*)$", line)
        if m and not line.startswith("```"):
            section = m.group(1)
        if line.startswith("```````````````````````````````` example"):
            number += 1
            i += 1
            md, html, cur = [], [], None
            cur = md
            while not lines[i].startswith("````````````````````````````````"):
                if lines[i] == ".":
                    cur = html
                else:
                    cur.append(lines[i])
                i += 1
            if section in SECTIONS:
                md_s = "\n".join(md) + "\n" if md else ""
                html_s = "\n".join(html) + "\n" if html else ""
                cases.append((number, section, md_s.replace("→", "\t"), html_s.replace("→", "\t")))
        i += 1
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_spec_cases.py from the GFM spec (github/cmark-gfm test/spec.txt).\n")
        f.write("pub const Case = struct { number: u32, section: []const u8, md: []const u8, html: []const u8 };\n\n")
        f.write("pub const cases = [_]Case{\n")
        for n, s, md, html in cases:
            f.write("    .{ .number = %d, .section = %s, .md = %s, .html = %s },\n" % (n, literal(s), literal(md), literal(html)))
        f.write("};\n")
    print(len(cases), "cases")


main(sys.argv[1], sys.argv[2])
