#!/usr/bin/env python3
"""Usage: gen_highlight_colors.py <primer-dark.json> <out.zig>

Reads the @primer/primitives dark theme token JSON and writes the prettylights
syntax colours as u24 constants.
"""
import json
import re
import sys

SOURCE = "https://cdn.jsdelivr.net/npm/@primer/primitives@latest/dist/docs/functional/themes/dark.json"
PREFIX = "color-prettylights-syntax-"


def main(src, out):
    with open(src, encoding="utf-8") as f:
        tokens = json.load(f)
    rows = []
    for key, tok in tokens.items():
        if not key.startswith(PREFIX):
            continue
        value = tok["value"]
        if not re.fullmatch(r"#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?", value):
            raise SystemExit(f"{key}: unsupported colour {value!r}")
        rows.append((key[len(PREFIX):].replace("-", "_"), value[1:7].lower()))
    if not rows:
        raise SystemExit("no prettylights syntax tokens found")
    rows.sort()
    lines = [
        f"// Generated by tools/gen_highlight_colors.py from {SOURCE}",
        "// Do not edit; the monthly workflow regenerates this file. Alpha is dropped.",
        "",
    ]
    lines += [f"pub const {name}: u24 = 0x{rgb};" for name, rgb in rows]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
