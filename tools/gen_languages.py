#!/usr/bin/env python3
"""Usage: gen_languages.py <languages.yml> <out.zig>

Reads github-linguist's languages.yml and writes a sorted table mapping every
case-folded language name and alias to the case-folded canonical language name.
"""
import sys

SOURCE = "https://raw.githubusercontent.com/github-linguist/linguist/main/lib/linguist/languages.yml"


def fold(s):
    return "".join(chr(ord(c) + 32) if "A" <= c <= "Z" else c for c in s)


def unquote(s):
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        s = s[1:-1]
        s = s.replace('\\"', '"').replace("\\\\", "\\")
    return s


def parse(path):
    langs = []
    key = ""
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line.strip() or line.startswith("#") or line == "---":
                continue
            if not line.startswith(" "):
                if not line.endswith(":"):
                    raise SystemExit(f"unexpected top-level line: {line!r}")
                langs.append((unquote(line[:-1]), [], []))
                key = ""
            elif line.startswith("  ") and not line.startswith("   "):
                stripped = line[2:]
                if stripped.startswith("- "):
                    if key == "aliases":
                        langs[-1][1].append(unquote(stripped[2:]))
                    elif key == "extensions":
                        langs[-1][2].append(unquote(stripped[2:]).lstrip("."))
                else:
                    key = stripped.split(":", 1)[0]
                    if key in ("aliases", "extensions") and stripped.rstrip() != key + ":":
                        raise SystemExit(f"inline list unsupported: {line!r}")
    return langs


RESTART = 16


def zig_bytes(data):
    """Zig string-literal chunks that spell `data` exactly."""
    lines = []
    for i in range(0, len(data), 64):
        chunk = []
        for b in data[i:i + 64]:
            ch = chr(b)
            if ch in '"\\':
                chunk.append("\\" + ch)
            elif 32 <= b < 127:
                chunk.append(ch)
            else:
                chunk.append("\\x%02x" % b)
        lines.append('    "' + "".join(chunk) + '"')
    return " ++\n".join(lines)


def int_type(limit):
    return "u8" if limit < 256 else "u16" if limit < 65536 else "u32"


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(src, out):
    langs = parse(src)
    ids = {}
    for n, (name, _, _) in enumerate(langs):
        ids[fold(name)] = n
    table = {k: v for k, v in ids.items()}
    for name, aliases, _ in langs:
        for a in aliases:
            table.setdefault(fold(a), ids[fold(name)])
    for name, _, exts in langs:
        for e in exts:
            if e:
                table.setdefault(fold(e), ids[fold(name)])
    rows = sorted(table.items(), key=lambda kv: kv[0].encode("utf-8"))
    if len(langs) > 0xFFFF:
        raise SystemExit("too many languages for u16 ids")

    blob = bytearray()
    restarts = []
    prev = b""
    for n, (key, lid) in enumerate(rows):
        k = key.encode("utf-8")
        if n % RESTART == 0:
            restarts.append(len(blob))
            prev = b""
        lcp = 0
        while lcp < min(len(prev), len(k)) and prev[lcp] == k[lcp]:
            lcp += 1
        if len(k) > 255:
            raise SystemExit(f"key too long: {key!r}")
        blob += bytes([lcp, len(k) - lcp]) + k[lcp:] + lid.to_bytes(2, "little")
        prev = k

    names = b"".join(fold(name).encode("utf-8") for name, _, _ in langs)
    name_offsets = [0]
    for name, _, _ in langs:
        name_offsets.append(name_offsets[-1] + len(fold(name).encode("utf-8")))

    rt = int_type(len(blob))
    stats = len(blob) + len(restarts) * (1 if len(blob) < 256 else 2 if len(blob) < 65536 else 4) + len(names) + 2 * len(name_offsets)
    print(f"{len(rows)} keys, {len(langs)} languages, packed tables {stats} bytes", file=sys.stderr)
    nt = int_type(len(names))
    lines = [
        f"// Generated by tools/gen_languages.py from {SOURCE}",
        "// Do not edit; the monthly workflow regenerates this file.",
        "// Keys: case-folded Linguist names, aliases and file extensions, sorted and front-coded",
        f"// in blocks of {RESTART}; each entry is lcp, suffix length, suffix, u16 language id.",
        "",
        'const std = @import("std");',
        "",
        f"const restarts = [_]{rt}{{ " + ", ".join(str(r) for r in restarts) + " };",
        "",
        "const blob =",
        zig_bytes(bytes(blob)) + ";",
        "",
        f"const name_offsets = [_]{nt}{{ " + ", ".join(str(o) for o in name_offsets) + " };",
        "",
        "const name_blob =",
        zig_bytes(names) + ";",
        "",
        "pub fn name(id: u16) []const u8 {",
        "    return name_blob[name_offsets[id]..name_offsets[id + 1]];",
        "}",
        "",
        "fn restartKey(i: usize) []const u8 {",
        "    const pos: usize = restarts[i];",
        "    return blob[pos + 2 ..][0..blob[pos + 1]];",
        "}",
        "",
        "/// `folded` must already be ASCII-lowercased.",
        "pub fn lookup(folded: []const u8) ?u16 {",
        "    var lo: usize = 0;",
        "    var hi: usize = restarts.len;",
        "    while (lo < hi) {",
        "        const mid = lo + (hi - lo) / 2;",
        "        if (std.mem.order(u8, restartKey(mid), folded) == .gt) hi = mid else lo = mid + 1;",
        "    }",
        "    if (lo == 0) return null;",
        "    var pos: usize = restarts[lo - 1];",
        "    const end: usize = if (lo < restarts.len) restarts[lo] else blob.len;",
        "    var key: [256]u8 = undefined;",
        "    while (pos < end) {",
        "        const keep = blob[pos];",
        "        const extra = blob[pos + 1];",
        "        @memcpy(key[keep..][0..extra], blob[pos + 2 ..][0..extra]);",
        "        pos += 2 + extra;",
        "        const id = @as(u16, blob[pos]) | @as(u16, blob[pos + 1]) << 8;",
        "        pos += 2;",
        "        if (std.mem.eql(u8, key[0 .. keep + extra], folded)) return id;",
        "    }",
        "    return null;",
        "}",
        "",
        "const expected = [_][2][]const u8{",
    ]
    lines += [f"    .{{ {lit(k)}, {lit(fold(langs[v][0]))} }}," for k, v in rows]
    lines += [
        "};",
        "",
        'test "every Linguist name, alias and extension resolves to the same language" {',
        "    for (expected) |e| {",
        "        const id = lookup(e[0]) orelse return error.TestUnexpectedResult;",
        "        try std.testing.expectEqualStrings(e[1], name(id));",
        "    }",
        '    try std.testing.expect(lookup("") == null);',
        '    try std.testing.expect(lookup("no such language") == null);',
        '    try std.testing.expect(lookup("zzzzzzzz") == null);',
        "}",
        "",
    ]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
