import json
import re
import sys

import packed_table

SAFE = re.compile(r"[A-Za-z0-9]+\Z")

TEST = '''
test "lookup" {
    try std.testing.expectEqualStrings("&", lookup("amp").?);
    try std.testing.expectEqualStrings("\\u{A0}", lookup("nbsp").?);
    try std.testing.expectEqualStrings("\\u{2267}\\u{338}", lookup("ngE").?);
    try std.testing.expect(lookup("notanentity") == null);
}
'''


def main():
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    entries = {}
    for key, value in data.items():
        if not (key.startswith("&") and key.endswith(";")):
            continue
        name = key[1:-1]
        if not SAFE.match(name):
            raise SystemExit("unexpected entity name: " + key)
        entries[name] = "".join(chr(cp) for cp in value["codepoints"]).encode("utf-8")
    header = "// Generated by tools/gen_entities.py from https://html.spec.whatwg.org/entities.json (WHATWG HTML Standard)."
    text, names_len, values_len, blocks, count = packed_table.source(entries, header, TEST.strip())
    packed_table.write(out, text)
    print("entries:", count, "names:", names_len, "values:", values_len)


if __name__ == "__main__":
    main()
