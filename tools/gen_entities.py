import json
import re
import sys

SAFE = re.compile(r"[A-Za-z0-9]+\Z")

TEST = '''
test "lookup" {
    try std.testing.expectEqualStrings("&", lookup("amp").?);
    try std.testing.expectEqualStrings("\\u{A0}", lookup("nbsp").?);
    try std.testing.expectEqualStrings("\\u{2267}\\u{338}", lookup("ngE").?);
    try std.testing.expect(lookup("notanentity") == null);
}
'''


def zig_text(codepoints):
    return "".join("\\u{%X}" % cp for cp in codepoints)


def main():
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    entries = {}
    for key, value in data.items():
        if not (key.startswith("&") and key.endswith(";")):
            continue
        name = key[1:-1]
        if not SAFE.match(name):
            raise SystemExit("unexpected entity name: " + key)
        entries[name] = zig_text(value["codepoints"])
    names = sorted(entries, key=lambda n: n.encode("ascii"))
    lines = [
        "// Generated by tools/gen_entities.py from https://html.spec.whatwg.org/entities.json (WHATWG HTML Standard).",
        "const std = @import(\"std\");",
        "",
        "const Entry = struct { name: []const u8, value: []const u8 };",
        "",
        "const entries = [_]Entry{",
    ]
    for name in names:
        lines.append('    .{ .name = "%s", .value = "%s" },' % (name, entries[name]))
    lines += [
        "};",
        "",
        "pub fn lookup(name: []const u8) ?[]const u8 {",
        "    var lo: usize = 0;",
        "    var hi: usize = entries.len;",
        "    while (lo < hi) {",
        "        const mid = lo + (hi - lo) / 2;",
        "        switch (std.mem.order(u8, entries[mid].name, name)) {",
        "            .lt => lo = mid + 1,",
        "            .gt => hi = mid,",
        "            .eq => return entries[mid].value,",
        "        }",
        "    }",
        "    return null;",
        "}",
        TEST.rstrip("\n"),
        "",
    ]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("entries:", len(names))


if __name__ == "__main__":
    main()
