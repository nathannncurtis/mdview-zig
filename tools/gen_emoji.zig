const std = @import("std");
const files = @import("files.zig");
const packed_table = @import("packed_table.zig");

const header = "// Generated by tools/gen_emoji.zig from github/gemoji db/emoji.json (https://github.com/github/gemoji, MIT, see emoji-LICENSE).";

const tests =
    \\test "lookup" {
    \\    try std.testing.expectEqualStrings("\u{1F389}", lookup("tada").?);
    \\    try std.testing.expectEqualStrings("\u{1F44D}", lookup("+1").?);
    \\    try std.testing.expect(lookup("notanemoji") == null);
    \\}
;

pub fn main(init: std.process.Init) !void {
    const a = try files.args(init, 2, "gen-emoji <emoji.json> <out.zig>");
    const arena = init.arena.allocator();
    const parsed = try std.json.parseFromSliceLeaky(std.json.Value, arena, try files.read(init.io, arena, a[0]), .{});
    var entries: std.ArrayList(packed_table.Entry) = .empty;
    var seen: std.StringHashMapUnmanaged(void) = .empty;
    for (parsed.array.items) |item| {
        const aliases = item.object.get("aliases") orelse continue;
        for (aliases.array.items) |alias| {
            const name = alias.string;
            if ((try seen.getOrPut(arena, name)).found_existing) {
                std.debug.print("duplicate alias: {s}\n", .{name});
                return error.DuplicateAlias;
            }
            for (name) |c| if (c >= 0x80) {
                std.debug.print("non-ASCII alias: {s}\n", .{name});
                return error.NonAscii;
            };
            try entries.append(arena, .{ .name = name, .value = item.object.get("emoji").?.string });
        }
    }
    const r = try packed_table.source(arena, entries.items, header, tests, packed_table.block_size);
    try files.write(init.io, a[1], r.text);
    std.debug.print("entries: {d} names: {d} values: {d}\n", .{ r.count, r.names_len, r.values_len });
}
