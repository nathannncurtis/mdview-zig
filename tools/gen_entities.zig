const std = @import("std");
const files = @import("files.zig");
const packed_table = @import("packed_table.zig");

const header = "// Generated by tools/gen_entities.zig from https://html.spec.whatwg.org/entities.json (WHATWG HTML Standard).";

const tests =
    \\test "lookup" {
    \\    try std.testing.expectEqualStrings("&", lookup("amp").?);
    \\    try std.testing.expectEqualStrings("\u{A0}", lookup("nbsp").?);
    \\    try std.testing.expectEqualStrings("\u{2267}\u{338}", lookup("ngE").?);
    \\    try std.testing.expect(lookup("notanentity") == null);
    \\}
;

pub fn main(init: std.process.Init) !void {
    const a = try files.args(init, 2, "gen-entities <entities.json> <out.zig>");
    const arena = init.arena.allocator();
    const parsed = try std.json.parseFromSliceLeaky(std.json.Value, arena, try files.read(init.io, arena, a[0]), .{});
    var entries: std.ArrayList(packed_table.Entry) = .empty;
    var it = parsed.object.iterator();
    while (it.next()) |kv| {
        const key = kv.key_ptr.*;
        if (!(key.len > 1 and key[0] == '&' and key[key.len - 1] == ';')) continue;
        const name = key[1 .. key.len - 1];
        if (name.len == 0) return error.BadEntity;
        for (name) |c| if (!std.ascii.isAlphanumeric(c)) {
            files.say(init.io, "unexpected entity name: {s}\n", .{key});
            return error.BadEntity;
        };
        var value: std.ArrayList(u8) = .empty;
        for (kv.value_ptr.object.get("codepoints").?.array.items) |cp| {
            var buf: [4]u8 = undefined;
            const n = try std.unicode.utf8Encode(@intCast(cp.integer), &buf);
            try value.appendSlice(arena, buf[0..n]);
        }
        try entries.append(arena, .{ .name = name, .value = value.items });
    }
    const r = try packed_table.source(arena, entries.items, header, tests, packed_table.block_size);
    try files.write(init.io, a[1], r.text);
    files.say(init.io, "entries: {d} names: {d} values: {d}\n", .{ r.count, r.names_len, r.values_len });
}
