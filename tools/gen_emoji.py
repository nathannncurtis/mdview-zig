import json
import sys


def zig_text(text):
    return "".join("\\u{%X}" % ord(ch) for ch in text)


def main():
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    entries = {}
    for item in data:
        for alias in item.get("aliases", []):
            if alias in entries:
                raise SystemExit("duplicate alias: " + alias)
            if not alias.isascii():
                raise SystemExit("non-ASCII alias: " + alias)
            entries[alias] = zig_text(item["emoji"])
    names = sorted(entries, key=lambda n: n.encode("ascii"))
    lines = [
        "// Generated by tools/gen_emoji.py from github/gemoji db/emoji.json (https://github.com/github/gemoji, MIT, see emoji-LICENSE).",
        "const std = @import(\"std\");",
        "",
        "const Entry = struct { alias: []const u8, value: []const u8 };",
        "",
        "const entries = [_]Entry{",
    ]
    for alias in names:
        lines.append('    .{ .alias = "%s", .value = "%s" },' % (alias, entries[alias]))
    lines += [
        "};",
        "",
        "pub fn lookup(alias: []const u8) ?[]const u8 {",
        "    var lo: usize = 0;",
        "    var hi: usize = entries.len;",
        "    while (lo < hi) {",
        "        const mid = lo + (hi - lo) / 2;",
        "        switch (std.mem.order(u8, entries[mid].alias, alias)) {",
        "            .lt => lo = mid + 1,",
        "            .gt => hi = mid,",
        "            .eq => return entries[mid].value,",
        "        }",
        "    }",
        "    return null;",
        "}",
        "",
        'test "lookup" {',
        '    try std.testing.expectEqualStrings("\\u{1F389}", lookup("tada").?);',
        '    try std.testing.expectEqualStrings("\\u{1F44D}", lookup("+1").?);',
        '    try std.testing.expect(lookup("notanemoji") == null);',
        "}",
        "",
    ]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("entries:", len(names))


if __name__ == "__main__":
    main()
