import json
import sys

import packed_table

TEST = '''test "lookup" {
    try std.testing.expectEqualStrings("\\u{1F389}", lookup("tada").?);
    try std.testing.expectEqualStrings("\\u{1F44D}", lookup("+1").?);
    try std.testing.expect(lookup("notanemoji") == null);
}'''


def main():
    src, out = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    entries = {}
    for item in data:
        for alias in item.get("aliases", []):
            if alias in entries:
                raise SystemExit("duplicate alias: " + alias)
            if not alias.isascii():
                raise SystemExit("non-ASCII alias: " + alias)
            entries[alias] = item["emoji"].encode("utf-8")
    header = "// Generated by tools/gen_emoji.py from github/gemoji db/emoji.json (https://github.com/github/gemoji, MIT, see emoji-LICENSE)."
    text, names_len, values_len, blocks, count = packed_table.source(entries, header, TEST)
    packed_table.write(out, text)
    print("entries:", count, "names:", names_len, "values:", values_len)


if __name__ == "__main__":
    main()
