const std = @import("std");
const Allocator = std.mem.Allocator;
const Writer = std.Io.Writer;
const files = @import("files");

const unicode_version = "17.0.0";

const Range = struct { lo: u32, hi: u32, name: []const u8 };

fn lessRange(_: void, a: Range, b: Range) bool {
    return a.lo < b.lo;
}

/// Turns a UCD value name into an enum tag: lower case, with `_` before a capital that follows a lower-case letter.
fn tag(a: Allocator, name: []const u8) Allocator.Error![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (name, 0..) |c, i| {
        if (i > 0 and std.ascii.isUpper(c) and std.ascii.isLower(name[i - 1])) try out.append(a, '_');
        try out.append(a, std.ascii.toLower(c));
    }
    return out.items;
}

fn parseHex(s: []const u8) !u32 {
    return std.fmt.parseInt(u32, std.mem.trim(u8, s, " "), 16);
}

/// Reads `XXXX..YYYY ; Value` lines. `field` is the index of the value column, `wanted` filters a property name in
/// column 1 when the file mixes properties.
fn readRanges(a: Allocator, text: []const u8, field: usize, wanted: ?[]const u8) ![]Range {
    var out: std.ArrayList(Range) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw[0..(std.mem.indexOfScalar(u8, raw, '#') orelse raw.len)], " \r\t");
        if (line.len == 0) continue;
        var cols: [3][]const u8 = .{ "", "", "" };
        var n: usize = 0;
        var it = std.mem.splitScalar(u8, line, ';');
        while (it.next()) |c| : (n += 1) {
            if (n >= cols.len) break;
            cols[n] = std.mem.trim(u8, c, " ");
        }
        if (n <= field) continue;
        if (wanted) |w| if (!std.mem.eql(u8, cols[1], w)) continue;
        const dots = std.mem.indexOf(u8, cols[0], "..");
        const lo = try parseHex(if (dots) |d| cols[0][0..d] else cols[0]);
        const hi = if (dots) |d| try parseHex(cols[0][d + 2 ..]) else lo;
        try out.append(a, .{ .lo = lo, .hi = hi, .name = cols[field] });
    }
    std.mem.sort(Range, out.items, {}, lessRange);
    return out.items;
}

fn emitEnum(a: Allocator, w: *Writer, type_name: []const u8, first: []const u8, ranges: []const Range) !void {
    var names: std.ArrayList([]const u8) = .empty;
    for (ranges) |r| {
        const t = try tag(a, r.name);
        var seen = false;
        for (names.items) |n| if (std.mem.eql(u8, n, t)) {
            seen = true;
        };
        if (!seen) try names.append(a, t);
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn f(_: void, x: []const u8, y: []const u8) bool {
            return std.mem.order(u8, x, y) == .lt;
        }
    }.f);
    try w.print("pub const {s} = enum(u8) {{\n    {s},\n", .{ type_name, first });
    for (names.items) |n| try w.print("    {s},\n", .{n});
    try w.writeAll("};\n\n");
}

fn emitTable(a: Allocator, w: *Writer, type_name: []const u8, table: []const u8, ranges: []const Range) !void {
    try w.print("pub const {s} = [_]struct {{ lo: u32, hi: u32, v: {s} }}{{\n", .{ table, type_name });
    for (ranges) |r| try w.print("    .{{ .lo = 0x{x}, .hi = 0x{x}, .v = .{s} }},\n", .{ r.lo, r.hi, try tag(a, r.name) });
    try w.writeAll("};\n\n");
}

pub fn generate(a: Allocator, grapheme_txt: []const u8, word_txt: []const u8, emoji_txt: []const u8, derived_txt: []const u8) ![]const u8 {
    var out: Writer.Allocating = .init(a);
    const w = &out.writer;
    try w.print("// Generated by tools/gen_segment.zig from Unicode {s} (GraphemeBreakProperty, WordBreakProperty, emoji-data, DerivedCoreProperties).\n\n", .{unicode_version});

    const grapheme = try readRanges(a, grapheme_txt, 1, null);
    try emitEnum(a, w, "GraphemeProp", "other", grapheme);
    try emitTable(a, w, "GraphemeProp", "grapheme", grapheme);

    const word = try readRanges(a, word_txt, 1, null);
    try emitEnum(a, w, "WordProp", "other", word);
    try emitTable(a, w, "WordProp", "word", word);

    const pict = try readRanges(a, emoji_txt, 1, null);
    try w.writeAll("pub const ext_pict = [_][2]u32{\n");
    for (pict) |r| {
        if (!std.mem.eql(u8, r.name, "Extended_Pictographic")) continue;
        try w.print("    .{{ 0x{x}, 0x{x} }},\n", .{ r.lo, r.hi });
    }
    try w.writeAll("};\n\n");

    const incb = try readRanges(a, derived_txt, 2, "InCB");
    try emitEnum(a, w, "Incb", "none", incb);
    try emitTable(a, w, "Incb", "incb", incb);
    return out.written();
}

pub fn main(init: std.process.Init) !void {
    const a = try files.args(init, 5, "gen-segment <GraphemeBreakProperty.txt> <WordBreakProperty.txt> <emoji-data.txt> <DerivedCoreProperties.txt> <out.zig>");
    var arena_state = std.heap.ArenaAllocator.init(init.gpa);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const text = try generate(
        arena,
        try files.read(init.io, arena, a[0]),
        try files.read(init.io, arena, a[1]),
        try files.read(init.io, arena, a[2]),
        try files.read(init.io, arena, a[3]),
    );
    try files.write(init.io, a[4], text);
}
