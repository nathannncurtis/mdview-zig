const std = @import("std");
const Allocator = std.mem.Allocator;
const json = std.json;
const frontmatter = @import("frontmatter");
const files = @import("files");

const source = "https://raw.githubusercontent.com/mermaid-js/mermaid/mermaid@12.2.0/packages/mermaid/src/schemas/config.schema.yaml";

const Value = json.Value;

// Mermaid's own list (.build/jsonSchema.ts): only these sections receive schema defaults.
const diagram_keys = [_][]const u8{
    "flowchart",     "swimlane", "agentflow", "sequence",   "gantt",    "journey",       "class",    "state",
    "er",            "pie",      "quadrantChart", "xyChart", "requirement", "mindmap",   "ishikawa", "kanban",
    "timeline",      "gitGraph", "c4",        "sankey",     "block",    "packet",        "treeView", "architecture",
    "eventmodeling", "radar",    "usecase",   "venn",       "cynefin",
};

fn get(v: Value, key: []const u8) ?Value {
    return if (v == .object) v.object.get(key) else null;
}

fn text(v: Value) ?[]const u8 {
    return if (v == .string) v.string else null;
}

const Gen = struct {
    a: Allocator,
    root: Value,

    fn resolve(g: Gen, schema: Value) ?Value {
        const ref = get(schema, "$ref") orelse return schema;
        var parts = std.mem.splitScalar(u8, text(ref) orelse return null, '/');
        if (!std.mem.eql(u8, parts.next() orelse return null, "#")) return null;
        var cur = g.root;
        while (parts.next()) |p| cur = get(cur, p) orelse return null;
        return cur;
    }

    fn copy(g: Gen, v: Value) Allocator.Error!Value {
        switch (v) {
            .array => |arr| {
                var out = json.Array.init(g.a);
                for (arr.items) |item| try out.append(try g.copy(item));
                return .{ .array = out };
            },
            .object => |o| {
                var out: json.ObjectMap = .empty;
                for (o.keys(), o.values()) |k, val| try out.put(g.a, k, try g.copy(val));
                return .{ .object = out };
            },
            else => return v,
        }
    }

    /// What ajv's `useDefaults` fills in: `default` values of `properties`, through `allOf`, and into objects already present.
    fn apply(g: Gen, schema: Value, target: *json.ObjectMap) Allocator.Error!void {
        if (get(schema, "allOf")) |all| if (all == .array) for (all.array.items) |item| {
            if (g.resolve(item)) |r| try g.apply(r, target);
        };
        const props = get(schema, "properties") orelse return;
        if (props != .object) return;
        for (props.object.keys(), props.object.values()) |k, p| {
            if (!target.contains(k)) {
                if (get(p, "default")) |d| try target.put(g.a, k, try g.copy(d));
            }
            if (target.getPtr(k)) |slot| if (slot.* == .object) {
                if (g.resolve(p)) |sub| try g.apply(sub, &slot.object);
            };
        }
    }
};

pub fn generate(a: Allocator, io: std.Io, schema_text: []const u8) ![]const u8 {
    const root = switch (try frontmatter.load(a, schema_text)) {
        .ok => |v| v,
        .err => |m| {
            files.say(io, "{s}\n", .{m});
            return error.BadYaml;
        },
    };
    const g: Gen = .{ .a = a, .root = root };
    const props = get(root, "properties") orelse return error.BadSchema;
    const defs = get(root, "$defs") orelse return error.BadSchema;
    const base = get(defs, "BaseDiagramConfig") orelse return error.BadSchema;
    const base_props = get(base, "properties") orelse return error.BadSchema;

    var top: json.ObjectMap = .empty;
    for (diagram_keys) |key| {
        const prop = get(props, key) orelse return error.BadSchema;
        const sub = g.resolve(prop) orelse return error.BadSchema;
        var section: json.ObjectMap = .empty;
        const sub_props = get(sub, "properties");
        if (get(sub, "required")) |req| if (req == .array) for (req.array.items) |r| {
            const name = text(r) orelse continue;
            if (sub_props) |sp| if (get(sp, name) != null) continue;
            if (get(base_props, name)) |bp| if (get(bp, "default")) |d| try section.put(a, name, try g.copy(d));
        };
        try g.apply(sub, &section);
        try top.put(a, key, .{ .object = section });
    }
    try g.apply(root, &top);

    var out: std.Io.Writer.Allocating = .init(a);
    const w = &out.writer;
    try w.print("// Generated by tools/gen/gen_mermaid_config.zig from {s}\n", .{source});
    try w.writeAll("pub const json =\n");
    var buf: std.Io.Writer.Allocating = .init(a);
    try json.Stringify.value(Value{ .object = top }, .{}, &buf.writer);
    var lines = std.mem.splitScalar(u8, buf.written(), '\n');
    while (lines.next()) |line| try w.print("    \\\\{s}\n", .{line});
    try w.writeAll("    ;\n");
    return out.written();
}

pub fn main(init: std.process.Init) !void {
    const a = try files.args(init, 2, "gen-mermaid-config <config.schema.yaml> <out.zig>");
    var arena_state = std.heap.ArenaAllocator.init(init.gpa);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    try files.write(init.io, a[1], try generate(arena, init.io, try files.read(init.io, arena, a[0])));
}
