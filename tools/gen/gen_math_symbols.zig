const std = @import("std");
const files = @import("files");

const Entry = struct { name: []const u8, cp: u21, class: []const u8, italic: bool, ams: bool, unicode: bool };

const Table = struct {
    names: std.StringArrayHashMapUnmanaged(Entry) = .empty,
    by_cp: std.AutoArrayHashMapUnmanaged(u21, []const u8) = .empty,
};

fn nameLess(_: void, a: Entry, b: Entry) bool {
    return std.mem.order(u8, a.name, b.name) == .lt;
}

const CpIdx = struct { cp: u21, idx: u32 };

fn cpLess(_: void, a: CpIdx, b: CpIdx) bool {
    return a.cp < b.cp;
}

pub fn main(init: std.process.Init) !void {
    const a = try files.args(init, 2, "gen-math-symbols <katex symbols.ts> <out.zig>");
    const arena = init.arena.allocator();
    const src = try files.read(init.io, arena, a[0]);

    var math: Table = .{};
    var text: Table = .{};
    var lines = std.mem.splitScalar(u8, src, '\n');
    while (lines.next()) |line| {
        if (!std.mem.startsWith(u8, line, "defineSymbol(")) continue;
        const args = (try splitArgs(arena, line["defineSymbol(".len..])) orelse continue;
        if (args.len < 5) continue;
        const class = classOf(args[2]) orelse continue;
        const table = if (std.mem.eql(u8, args[0], "math")) &math else if (std.mem.eql(u8, args[0], "text")) &text else continue;
        const replace = (try literal(arena, args[3])) orelse continue;
        const name = (try literal(arena, args[4])) orelse continue;
        if (name.len == 0 or replace.len == 0) continue;
        const view = try std.unicode.Utf8View.init(replace);
        var it = view.iterator();
        const cp = it.nextCodepoint() orelse continue;
        if (it.nextCodepoint() != null) continue;
        const accept = args.len > 5 and std.mem.eql(u8, args[5], "true");
        const entry: Entry = .{
            .name = name,
            .cp = cp,
            .class = class.name,
            .italic = class.italic,
            .ams = std.mem.eql(u8, args[1], "ams"),
            .unicode = accept,
        };
        try table.names.put(arena, name, entry);
        if (accept) try table.by_cp.put(arena, cp, name);
    }

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("// Generated by tools/gen/gen_math_symbols.zig from KaTeX src/symbols.ts (MIT).\n");
    try w.writeAll("// Do not edit; regenerate with `zig build gen-math-symbols -- <symbols.ts> src/math/symbols.zig`.\n\n");
    try w.writeAll("const std = @import(\"std\");\nconst tree = @import(\"tree.zig\");\n\n");
    try w.writeAll("pub const Entry = struct { name: []const u8, cp: u21, class: tree.Class, italic: bool, ams: bool };\n\n");
    try w.writeAll("const CpIdx = struct { cp: u21, idx: u16 };\n\n");
    try emit(arena, w, "math", &math, true);
    try emit(arena, w, "text", &text, false);
    try w.writeAll(
        \\fn find(entries: []const Entry, name: []const u8) ?Entry {
        \\    var lo: usize = 0;
        \\    var hi: usize = entries.len;
        \\    while (lo < hi) {
        \\        const mid = lo + (hi - lo) / 2;
        \\        switch (std.mem.order(u8, entries[mid].name, name)) {
        \\            .eq => return entries[mid],
        \\            .lt => lo = mid + 1,
        \\            .gt => hi = mid,
        \\        }
        \\    }
        \\    return null;
        \\}
        \\
        \\fn findCp(entries: []const Entry, index: []const CpIdx, cp: u21) ?Entry {
        \\    var lo: usize = 0;
        \\    var hi: usize = index.len;
        \\    while (lo < hi) {
        \\        const mid = lo + (hi - lo) / 2;
        \\        if (index[mid].cp == cp) return entries[index[mid].idx];
        \\        if (index[mid].cp < cp) lo = mid + 1 else hi = mid;
        \\    }
        \\    return null;
        \\}
        \\
        \\/// `name` includes the backslash for control sequences.
        \\pub fn lookupMath(name: []const u8) ?Entry {
        \\    return find(&math, name);
        \\}
        \\
        \\pub fn lookupText(name: []const u8) ?Entry {
        \\    return find(&text, name);
        \\}
        \\
        \\pub fn lookupMathCp(cp: u21) ?Entry {
        \\    return findCp(&math, &math_cp, cp);
        \\}
        \\
    );
    try files.write(init.io, a[1], out.written());
}

fn emit(arena: std.mem.Allocator, w: *std.Io.Writer, label: []const u8, t: *Table, with_cp_index: bool) !void {
    const entries = try arena.dupe(Entry, t.names.values());
    std.mem.sort(Entry, entries, {}, nameLess);
    try w.print("pub const {s} = [_]Entry{{\n", .{label});
    for (entries) |e| {
        try w.writeAll("    .{ .name = \"");
        for (e.name) |c| {
            if (c == '\\' or c == '"') try w.writeByte('\\');
            try w.writeByte(c);
        }
        try w.print("\", .cp = 0x{x}, .class = .{s}, .italic = {}, .ams = {} }},\n", .{ e.cp, e.class, e.italic, e.ams });
    }
    try w.writeAll("};\n\n");
    if (!with_cp_index) return;

    var idx: std.ArrayList(CpIdx) = .empty;
    for (t.by_cp.keys(), t.by_cp.values()) |cp, name| {
        for (entries, 0..) |e, i| {
            if (std.mem.eql(u8, e.name, name)) {
                try idx.append(arena, .{ .cp = cp, .idx = @intCast(i) });
                break;
            }
        }
    }
    std.mem.sort(CpIdx, idx.items, {}, cpLess);
    try w.print("const {s}_cp = [_]CpIdx{{\n", .{label});
    for (idx.items) |c| try w.print("    .{{ .cp = 0x{x}, .idx = {d} }},\n", .{ c.cp, c.idx });
    try w.writeAll("};\n\n");
}

const Class = struct { name: []const u8, italic: bool };

fn classOf(group: []const u8) ?Class {
    const map = [_]struct { []const u8, Class }{
        .{ "rel", .{ .name = "rel", .italic = false } },
        .{ "bin", .{ .name = "bin", .italic = false } },
        .{ "open", .{ .name = "open", .italic = false } },
        .{ "close", .{ .name = "close", .italic = false } },
        .{ "punct", .{ .name = "punct", .italic = false } },
        .{ "inner", .{ .name = "inner", .italic = false } },
        .{ "op", .{ .name = "op", .italic = false } },
        .{ "textord", .{ .name = "ord", .italic = false } },
        .{ "mathord", .{ .name = "ord", .italic = true } },
    };
    for (map) |m| if (std.mem.eql(u8, m[0], group)) return m[1];
    return null;
}

fn splitArgs(arena: std.mem.Allocator, s: []const u8) !?[]const []const u8 {
    var args: std.ArrayList([]const u8) = .empty;
    var i: usize = 0;
    while (i < s.len) {
        while (i < s.len and (s[i] == ' ' or s[i] == ',')) i += 1;
        if (i >= s.len or s[i] == ')') break;
        const start = i;
        if (s[i] == '"' or s[i] == '\'') {
            const q = s[i];
            i += 1;
            while (i < s.len and s[i] != q) i += if (s[i] == '\\') 2 else 1;
            if (i >= s.len) return null;
            i += 1;
        } else {
            while (i < s.len and s[i] != ',' and s[i] != ')') i += 1;
        }
        try args.append(arena, s[start..i]);
    }
    return args.items;
}

fn literal(arena: std.mem.Allocator, s: []const u8) !?[]const u8 {
    if (s.len < 2 or (s[0] != '"' and s[0] != '\'')) return null;
    var out: std.ArrayList(u8) = .empty;
    var i: usize = 1;
    while (i < s.len - 1) {
        if (s[i] != '\\') {
            try out.append(arena, s[i]);
            i += 1;
            continue;
        }
        i += 1;
        switch (s[i]) {
            'u' => {
                const cp = try std.fmt.parseInt(u21, s[i + 1 .. i + 5], 16);
                var buf: [4]u8 = undefined;
                const n = try std.unicode.utf8Encode(cp, &buf);
                try out.appendSlice(arena, buf[0..n]);
                i += 5;
            },
            else => {
                try out.append(arena, s[i]);
                i += 1;
            },
        }
    }
    return out.items;
}
