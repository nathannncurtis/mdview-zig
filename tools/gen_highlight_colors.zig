const std = @import("std");
const files = @import("files.zig");

const source = "https://cdn.jsdelivr.net/npm/@primer/primitives@latest/dist/docs/functional/themes/dark.json";
const prefix = "color-prettylights-syntax-";

const Row = struct { name: []u8, rgb: []u8 };

fn rowLess(_: void, a: Row, b: Row) bool {
    return std.mem.order(u8, a.name, b.name) == .lt;
}

pub fn main(init: std.process.Init) !void {
    const a = try files.args(init, 2, "gen-highlight-colors <primer-dark.json> <out.zig>");
    const arena = init.arena.allocator();
    const tokens = try std.json.parseFromSliceLeaky(std.json.Value, arena, try files.read(init.io, arena, a[0]), .{});
    var rows: std.ArrayList(Row) = .empty;
    var it = tokens.object.iterator();
    while (it.next()) |kv| {
        const key = kv.key_ptr.*;
        if (!std.mem.startsWith(u8, key, prefix)) continue;
        const value = kv.value_ptr.object.get("value").?.string;
        if (!validColour(value)) {
            std.debug.print("{s}: unsupported colour {s}\n", .{ key, value });
            return error.BadColour;
        }
        const name = try arena.dupe(u8, key[prefix.len..]);
        std.mem.replaceScalar(u8, name, '-', '_');
        try rows.append(arena, .{ .name = name, .rgb = try std.ascii.allocLowerString(arena, value[1..7]) });
    }
    if (rows.items.len == 0) return error.NoTokens;
    std.mem.sort(Row, rows.items, {}, rowLess);

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.print("// Generated by tools/gen_highlight_colors.zig from {s}\n", .{source});
    try w.writeAll("// Do not edit; the monthly workflow regenerates this file. Alpha is dropped.\n\n");
    for (rows.items) |r| try w.print("pub const {s}: u24 = 0x{s};\n", .{ r.name, r.rgb });
    try files.write(init.io, a[1], out.written());
}

fn validColour(v: []const u8) bool {
    if ((v.len != 7 and v.len != 9) or v[0] != '#') return false;
    for (v[1..]) |c| if (!std.ascii.isHex(c)) return false;
    return true;
}
